const PRIMARY_CODE_MASK: c_int = 0xff;

pub fn result_code_name(extended_code: c_int) -> Option<&'static str> {
	named(extended_code).or_else(|| named(extended_code & PRIMARY_CODE_MASK))
}

#[cfg(test)]
mod tests {
	use super::*;

	#[test]
	fn an_extended_code_reads_as_its_sqlite_name() {
		assert_eq!(
			result_code_name(ffi::SQLITE_CONSTRAINT_FOREIGNKEY),
			Some("SQLITE_CONSTRAINT_FOREIGNKEY")
		);
	}

	#[test]
	fn an_extended_code_sqlite_does_not_name_falls_back_to_its_primary_code() {
		assert_eq!(result_code_name(ffi::SQLITE_CONSTRAINT | (99 << 8)), Some("SQLITE_CONSTRAINT"));
	}
}
