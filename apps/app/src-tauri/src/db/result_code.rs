use std::os::raw::c_int;

use rusqlite::ffi;

macro_rules! named_codes {
	($($code:ident),+ $(,)?) => {
		fn named(code: c_int) -> Option<&'static str> {
			match code {
				$(ffi::$code => Some(stringify!($code)),)+
				_ => None,
			}
		}
	};
}

